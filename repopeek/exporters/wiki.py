"""Agent-crawlable markdown wiki exporter: index.md + community articles with cross-links."""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import networkx as nx

from repopeek.analyze import god_nodes


def _slugify(text: str) -> str:
    """Creates safe slug for markdown filenames."""
    s = re.sub(r"[^A-Za-z0-9_-]", "_", text).strip("_")
    return s or "article"


def export_markdown_wiki(
    graph: nx.DiGraph,
    output_dir: Path | str,
    project_name: str = "RepoPeek Project",
) -> Path:
    """Exports an agent-crawlable static markdown documentation wiki."""
    wiki_path = Path(output_dir).resolve()
    wiki_path.mkdir(parents=True, exist_ok=True)

    # 1. Group nodes by community
    communities: dict[int, list[str]] = {}
    for n, d in graph.nodes(data=True):
        comm = d.get("community", 0)
        communities.setdefault(comm, []).append(n)

    # 2. Generate per-community articles
    community_meta: list[dict[str, Any]] = []

    for cid, members in sorted(communities.items()):
        comm_title = f"Community {cid}"
        slug = f"community_{cid}"
        art_path = wiki_path / f"{slug}.md"

        # Tally files in community
        comm_files = sorted(list({graph.nodes[m].get("file_path", "") for m in members if graph.nodes[m].get("file_path")}))

        # Collect boundary edges
        inbound_callers: list[tuple[str, str, str]] = []
        outbound_dependencies: list[tuple[str, str, str]] = []

        for m in members:
            for u, _, edata in graph.in_edges(m, data=True):
                if u not in members:
                    inbound_callers.append((u, m, edata.get("relation", "DEPENDS_ON")))
            for _, v, edata in graph.out_edges(m, data=True):
                if v not in members:
                    outbound_dependencies.append((m, v, edata.get("relation", "DEPENDS_ON")))

        # Compose article
        lines = [
            f"# {comm_title}",
            "",
            f"**Total Symbols**: {len(members)} | **Key Files**: {len(comm_files)}",
            "",
            "## Primary Source Files",
        ]
        for f in comm_files[:15]:
            lines.append(f"- `{f}`")

        lines.append("\n## Core Member Symbols")
        for m in members[:30]:
            d = graph.nodes[m]
            lbl = d.get("label", m)
            kind = d.get("kind", "symbol")
            fp = d.get("file_path", "")
            lines.append(f"- **`{lbl}`** (`{kind}`) in `{fp}`")

        if inbound_callers:
            lines.append(f"\n## Inbound External Callers ({len(inbound_callers)})")
            for u, m, rel in inbound_callers[:15]:
                u_lbl = graph.nodes[u].get("label", u)
                m_lbl = graph.nodes[m].get("label", m)
                lines.append(f"- `{u_lbl}` --[{rel}]--> `{m_lbl}`")

        if outbound_dependencies:
            lines.append(f"\n## Outbound External Dependencies ({len(outbound_dependencies)})")
            for m, v, rel in outbound_dependencies[:15]:
                m_lbl = graph.nodes[m].get("label", m)
                v_lbl = graph.nodes[v].get("label", v)
                lines.append(f"- `{m_lbl}` --[{rel}]--> `{v_lbl}`")

        lines.append("\n---\n*Back to [Wiki Index](index.md)*\n")

        art_path.write_text("\n".join(lines), encoding="utf-8")
        community_meta.append({
            "cid": cid,
            "title": comm_title,
            "slug": slug,
            "symbols_count": len(members),
            "files_count": len(comm_files),
        })

    # 3. Generate index.md
    gods = god_nodes(graph, top_n=5)
    index_lines = [
        f"# {project_name} Knowledge Wiki",
        "",
        "This agent-crawlable knowledge base maps the architectural clusters, dependencies, and hub symbols across the codebase.",
        "",
        "## Architectural Communities",
        "",
        "| Community | Symbol Count | File Count | Documentation Article |",
        "|---|---|---|---|",
    ]

    for cm in community_meta:
        index_lines.append(f"| Community {cm['cid']} | {cm['symbols_count']} | {cm['files_count']} | [{cm['title']}]({cm['slug']}.md) |")

    if gods:
        index_lines.append("\n## Architectural God Nodes (Primary Hubs)")
        index_lines.append("")
        for g in gods:
            index_lines.append(f"- **`{g['label']}`** (`{g['kind']}`): {g['total_degree']} total connections in `{g['file_path']}`")

    index_lines.append("\n---\n*Generated by RepoPeek V2 Agent Wiki Exporter.*")
    (wiki_path / "index.md").write_text("\n".join(index_lines), encoding="utf-8")

    return wiki_path
